"""The Planet Simulator module the sim, the mesher and the tools import, so nobody copies a class list by hand again: every
Planet Simulator record as data (DATA, by kind and key; basis notes left out) and the functions of planet_lod.py (classify,
strength, match, context) bound to it.

    python3 tools/standards/planet_lod_module.py             # write standards/PlanetSim/generated/planet_lod_words.py
    python3 tools/standards/planet_lod_module.py --check     # exit 1 when the written module is out of date

Use: sys.path.insert(0, "<fso>/standards/PlanetSim/generated"); import planet_lod_words as W;
W.classify("climate", {"fields": {...}}); W.match({...}); W.context_of("100-km"); W.DATA["planet-field"]["planet-field.rain"]["unit"].
Generated: change the records, then run this again.
"""
import hashlib, inspect, json, os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import planet_lod  # noqa: E402

TREE = os.path.join(os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))), "standards")
OUT = os.path.join(TREE, "PlanetSim", "generated", "planet_lod_words.py")
FUNCS = ("_key", "_value", "_class", "holds", "classify", "strength", "match", "_refs", "context")


def render():
    R = planet_lod.load(TREE)
    data = {kind: {k: {x: v for x, v in d.items() if x != "basis"} for k, d in rs.items()} for kind, rs in R.items()}
    body = json.dumps(data, ensure_ascii=False, sort_keys=True, separators=(",", ":"))
    h = hashlib.sha256(body.encode()).hexdigest()[:16]
    src = "\n\n".join(inspect.getsource(getattr(planet_lod, f)) for f in FUNCS)
    wrap = '''

def classify_in(layer, sig):
    return classify(DATA, layer, sig)


def match_place(sig, top=10, family=None):
    return match(DATA, sig, top, family)


def context_of(target):
    return context(DATA, target)
'''
    return (f'"""Planet Simulator words, generated by tools/standards/planet_lod_module.py from standards/PlanetSim (data {h}). Do not edit:\n'
            'change the records and run it again. classify_in(layer, sig), match_place(sig), context_of(target); DATA by kind and key."""\n'
            f"import json\n\nDATA_SHA = \"{h}\"\nLINKS = {planet_lod.LINKS!r}\nDATA = json.loads({body!r})\n\n\n" + src + wrap)


def main(argv):
    text = render()
    if "--check" in argv:
        ok = os.path.exists(OUT) and open(OUT, encoding="utf-8").read() == text
        print("up to date" if ok else f"out of date: run {os.path.relpath(__file__)}")
        sys.exit(0 if ok else 1)
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    open(OUT, "w", encoding="utf-8").write(text)
    print(f"{OUT}: {len(text) / 1024:.0f} KB")


if __name__ == "__main__":
    main(sys.argv)
