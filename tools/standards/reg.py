"""reg: the registry keeper's command line. Routine registry work goes through it, not through one-off scripts.

    python3 tools/standards/reg.py find <words>                 # records whose key or name has the words
    python3 tools/standards/reg.py show <key>                   # its file, whether it is generated, its YAML
    python3 tools/standards/reg.py new <kind> <slug> [--root=SFO] [--folder=<dir>]   # a record from its schema's required fields; --folder a subfolder of the kind's (hydrology) or a path from a root
    python3 tools/standards/reg.py set <key> <dotted.path> <yaml value>              # change one field of a hand-written record
    python3 tools/standards/reg.py check [--engine] [--page <key>...]                # every check, in order; exit 1 on any failure
    python3 tools/standards/reg.py ship "<message>"            # commit here, merge into fso, refresh the page there; prints the real hashes
    python3 tools/standards/reg.py validate <key>...            # an installed model: its record's model path, the gap check, the engine's registry reader
    python3 tools/standards/reg.py page [<key>]                 # open the registry page (at a record)
    python3 tools/standards/reg.py mail                         # the registry's unread mail (agentmsg --as registry)

check runs: validate.py (every record against its schema), build.py (its own cross-checks; it writes the page and the
generated module), planet_lod_module.py --check, fit_layout.py (every plant layout laid of runs), kit_works.py --check
(every KIT- stock made by some module), with --engine the
engine's registry reader (cargo check of crates/core/world, under ~/bin/capped), with --page a headless Chromium load
of each page key, failing on any JavaScript error. A generated record (its header says "Written by tools/...") is
changed in its generator, never here: set refuses it.
"""
import glob, os, re, subprocess, sys
import yaml

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
TREE = os.path.join(ROOT, "standards")
TRAILER = "\n\nCo-Authored-By: Claude Opus 5.5 <noreply@anthropic.com>"


def sh(cmd, cwd=ROOT, check=False, timeout=1500):
    r = subprocess.run(cmd, cwd=cwd, shell=isinstance(cmd, str), capture_output=True, text=True, timeout=timeout)
    if check and r.returncode:
        sys.exit(f"failed: {cmd}\n{r.stdout[-2000:]}{r.stderr[-2000:]}")
    return r


def records():
    for f in glob.glob(os.path.join(TREE, "**", "*.yaml"), recursive=True):
        if "/schema/" in f:
            continue
        try:
            d = yaml.safe_load(open(f, encoding="utf-8")) or {}
        except Exception:
            continue
        i = d.get("identity") if isinstance(d, dict) and isinstance(d.get("identity"), dict) else {}
        if i.get("key"):
            yield i["key"], i.get("name", ""), f, d


def find_key(key):
    hit = next(((k, n, f, d) for k, n, f, d in records() if k == key), None)
    if not hit:
        sys.exit(f"no record {key}")
    return hit


def generated(path):
    head = open(path, encoding="utf-8").read(400)
    m = re.search(r"Written by (tools/standards/\S+)", head)
    return m.group(1).rstrip(":") if m else None


def cmd_find(words):
    ws = [w.lower() for w in words]
    for k, n, f, _ in sorted(records()):
        if all(w in f"{k} {n}".lower() for w in ws):
            print(f"{k:<55} {n}")


def cmd_show(key):
    k, n, f, d = find_key(key)
    g = generated(f)
    print(f"# {os.path.relpath(f, ROOT)}" + (f"   (generated by {g}: change it there)" if g else "   (hand-written: edit here or with reg set)"))
    print(open(f, encoding="utf-8").read())


def schema_for(kind):
    for s in glob.glob(os.path.join(TREE, "**", "schema", "*.schema.yaml"), recursive=True):
        d = yaml.safe_load(open(s)) or {}
        if kind in (d.get("x-kind") or []):
            return s, d
    sys.exit(f"no schema says x-kind {kind}")


def cmd_new(kind, slug, opt):
    spath, sch = schema_for(kind)
    folder = opt.get("folder")
    m = re.match(r"standards/([^<]+?)/<", sch.get("description", ""))      # (the schema says where its records lie)
    home = os.path.join(TREE, m.group(1)) if m else None
    if not folder:
        f = next((f for k, _, f, _ in records() if k.split(".")[0] == kind), None)
        folder = home or (os.path.dirname(f) if f else None)
        if not folder:
            sys.exit(f"no {kind} record yet to tell its folder: pass --folder=<dir>")
    elif os.path.isdir(os.path.join(TREE, folder.split("/")[0])) and folder.split("/")[0][:1].isupper():
        folder = os.path.join(TREE, folder)        # (a path from a root: PlanetSim/metadata/...)
    elif home:
        folder = os.path.join(home, folder)        # (a subfolder of the kind's own: hydrology)
    else:
        sys.exit(f"--folder={folder}: give it from a root (PlanetSim/metadata/...)")
    path = os.path.join(folder, slug + ".yaml")
    if os.path.exists(path):
        sys.exit(f"{os.path.relpath(path, ROOT)} exists")
    rel = os.path.relpath(spath, folder)
    d = {"identity": {"key": f"{kind}.{slug}", "name": slug.replace("-", " ").capitalize()}}
    for k in sch.get("required", []):
        if k != "identity":
            d[k] = None
    for k in ((sch.get("properties") or {}).get("identity", {}).get("required") or []):
        d["identity"].setdefault(k, "TODO")
    os.makedirs(folder, exist_ok=True)
    open(path, "w").write(f"# yaml-language-server: $schema={rel}\n" + yaml.safe_dump(d, sort_keys=False, allow_unicode=True, width=200))
    print(f"wrote {os.path.relpath(path, ROOT)}: fill the TODO and null fields, then reg check")


def cmd_set(key, dotted, value):
    k, n, f, d = find_key(key)
    g = generated(f)
    if g:
        sys.exit(f"{os.path.relpath(f, ROOT)} is generated by {g}: change it there and rerun it")
    head = open(f, encoding="utf-8").read().split("\n", 1)[0]
    v = yaml.safe_load(value)
    node = d
    parts = dotted.split(".")
    for p_ in parts[:-1]:
        node = node[int(p_)] if isinstance(node, list) else node.setdefault(p_, {})
    if isinstance(node, list) and parts[-1] == "+":      # (a path ending in + appends to the list)
        old = None
        node.append(v)
    elif isinstance(node, list):
        old = node[int(parts[-1])]
        node[int(parts[-1])] = v
    else:
        old = node.get(parts[-1])
        node[parts[-1]] = v
    open(f, "w", encoding="utf-8").write((head + "\n" if head.startswith("#") else "") + yaml.safe_dump(d, sort_keys=False, allow_unicode=True, width=230))
    print(f"{key} {dotted}: {old!r} -> {v!r}   (comments in the file, other than its first line, are not kept)")


def pagetest(keys, html):
    bad = 0
    for key in keys:
        r = sh(["chromium", "--headless=new", "--disable-gpu", "--no-sandbox", "--enable-logging=stderr", "--v=0", "--virtual-time-budget=4000",
                "--dump-dom", f"file://{html}#{key}"], timeout=90)
        errs = [l for l in r.stderr.splitlines() if "Uncaught" in l]
        dom = re.sub(r"<script.*?</script>", "", r.stdout, flags=re.S)
        body = dom[dom.find('id="detail"'):]
        links = len(re.findall(r'<a data-k="', body))
        print(f"  page {key}: {'JS ERROR ' + errs[0][:160] if errs else 'ok'} ({links} links)")
        bad += bool(errs)
    return bad


def cmd_check(opt, pages):
    steps = [("validate", [sys.executable, "tools/standards/validate.py"], lambda o: o.strip().splitlines()[-1].startswith("0 thing")),
             ("build", [sys.executable, "tools/standards/build.py"], None),
             ("module", [sys.executable, "tools/standards/planet_lod_module.py", "--check"], None),
             ("fit", [sys.executable, "tools/standards/fit_layout.py"], lambda o: not re.search(r"[1-9]\d* fault\(s\)", o)),
             ("makers", [sys.executable, "tools/standards/kit_works.py", "--check"], lambda o: not re.search(r"[1-9]\d* fault\(s\)", o))]
    failed = 0
    for name, cmd, ok in steps:
        r = sh(cmd)
        out = r.stdout + r.stderr
        good = r.returncode == 0 and (ok(out) if ok else True)
        last = [l for l in out.strip().splitlines() if l.strip()][-1:] or [""]
        print(f"{'ok  ' if good else 'FAIL'} {name}: {last[0][:180]}")
        if not good:
            failed += 1
            print("\n".join(l for l in out.splitlines() if re.search(r"fault|problem|Error|unknown|not a|no record|Trace", l))[:3000])
    if opt.get("engine"):
        r = sh("timeout 1500 ~/bin/capped cargo check -q", cwd=os.path.join(ROOT, "crates/core/world"))
        errs = [l for l in (r.stdout + r.stderr).splitlines() if "panicked" in l or l.startswith("error")]
        print(f"{'FAIL' if errs or r.returncode else 'ok  '} engine registry reader" + (": " + errs[0][:200] if errs else ""))
        failed += bool(errs or r.returncode)
    if pages:
        failed += pagetest(pages, os.path.join(TREE, "index.html"))
    print("all checks pass" if not failed else f"{failed} check(s) failed")
    sys.exit(1 if failed else 0)


def fso_worktree():
    out = sh("git worktree list --porcelain").stdout
    cur = None
    for line in out.splitlines():
        if line.startswith("worktree "):
            cur = line.split(" ", 1)[1]
        if line.strip() == "branch refs/heads/fso":
            return cur
    sys.exit("no worktree has branch fso checked out")


GENERATED = ("standards/index.html", "standards/changes.yaml", "standards/game-keys.yaml", "standards/PlanetSim/generated/")


def resolve_generated():
    """A rebase stopped on conflicts: when they are all in generated files, take fso's copies, rebuild, continue."""
    for _ in range(50):
        bad = sh("git diff --name-only --diff-filter=U").stdout.split()
        if not bad:
            return True
        if any(not f.startswith(GENERATED) for f in bad):
            return False
        sh(["git", "checkout", "--ours", "--"] + bad)
        sh([sys.executable, "tools/standards/build.py"])
        sh("git add -A")
        r = subprocess.run("git rebase --continue", cwd=ROOT, shell=True, capture_output=True, text=True, env={**os.environ, "GIT_EDITOR": "true"})
        if r.returncode == 0 and not sh("git diff --name-only --diff-filter=U").stdout.strip():
            return True
    return False


def cmd_ship(message):
    branch = sh("git rev-parse --abbrev-ref HEAD").stdout.strip()
    fso = fso_worktree()
    if sh("git status --porcelain").stdout.strip():
        sh("git add -A", check=True)
        sh(["git", "commit", "-q", "-m", message + TRAILER], check=True)
    if os.path.realpath(fso) != os.path.realpath(ROOT):
        sh("git pull -q --rebase --autostash", cwd=fso)
        if sh(["git", "merge", "-q", "--ff-only", branch], cwd=fso).returncode:
            if sh("git rebase -q fso").returncode and not resolve_generated():
                sys.exit("rebase onto fso stopped on a conflict in a hand-written file: resolve it, git rebase --continue, ship again")
            if sh("git merge-base --is-ancestor fso HEAD").returncode:
                r = sh("git status -sb")
                sys.exit("the rebase onto fso did not complete (no conflict to resolve): " + (r.stdout.splitlines() or [""])[0] + ". Run git rebase fso here, then ship again")
            sh(["git", "merge", "-q", "--ff-only", branch], cwd=fso, check=True)
    sh([sys.executable, "tools/standards/build.py"], cwd=fso)
    sh("git add standards/index.html standards/changes.yaml standards/game-keys.yaml standards/PlanetSim/generated", cwd=fso)
    if sh("git diff --cached --quiet", cwd=fso).returncode:
        sh(["git", "commit", "-q", "-m", "Refresh the registry page" + TRAILER], cwd=fso, check=True)
    if os.path.realpath(fso) != os.path.realpath(ROOT):
        sh("git merge -q --ff-only fso")
    log = sh("git log --format=%h\\ %s -3", cwd=fso).stdout
    print("fso now:\n" + "\n".join("  " + l[:100] for l in log.splitlines()))
    print("quote hashes from these lines only")


def cmd_validate(keys):
    import json
    bad = 0
    for key in keys:
        k, n, f, d = find_key(key)
        path = (d.get("visual") or {}).get("path")
        r = sh([sys.executable, "tools/standards/next_asset.py", "--gap", key])
        try:
            g = json.loads(r.stdout[r.stdout.find("{"):])
        except Exception:
            g = {}
        if g.get("gaps"):
            print("     " + "; ".join(f"{x['verdict']} {x['what']}: {x['detail']}" for x in g["gaps"])[:400])
        ok = bool(path) and g.get("verdict") == "none" and not g.get("gaps")
        print(f"{'ok  ' if ok else 'FAIL'} {key}: model {path or 'none'}, installed v{g.get('installed')}, verdict {g.get('verdict')}, gaps {len(g.get('gaps') or [])}")
        bad += not ok
    r = sh("timeout 1500 ~/bin/capped cargo check -q", cwd=os.path.join(ROOT, "crates/core/world"))
    errs = [l for l in (r.stdout + r.stderr).splitlines() if "panicked" in l or l.startswith("error")]
    print(f"{'FAIL' if errs or r.returncode else 'ok  '} engine registry reader" + (": " + errs[0][:200] if errs else ""))
    sys.exit(1 if bad or errs or r.returncode else 0)


def main(argv):
    if len(argv) < 2:
        sys.exit(__doc__)
    opt = {a.split("=", 1)[0].lstrip("-"): (a.split("=", 1)[1] if "=" in a else True) for a in argv[2:] if a.startswith("--")}
    pos = [a for a in argv[2:] if not a.startswith("--")]
    c = argv[1]
    if c == "find":
        cmd_find(pos)
    elif c == "show":
        cmd_show(pos[0])
    elif c == "new":
        cmd_new(pos[0], pos[1], opt)
    elif c == "set":
        cmd_set(pos[0], pos[1], " ".join(pos[2:]))
    elif c == "check":
        pages = argv[argv.index("--page") + 1:] if "--page" in argv else []
        cmd_check(opt, [p for p in pages if not p.startswith("--")])
    elif c == "ship":
        cmd_ship(" ".join(pos))
    elif c == "validate":
        cmd_validate(pos)
    elif c == "page":
        target = os.path.join(TREE, "index.html") + (f"#{pos[0]}" if pos else "")
        subprocess.Popen(["xdg-open", "file://" + target], stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    elif c == "mail":
        print(sh("agentmsg inbox --as registry").stdout)
    else:
        sys.exit(__doc__)


if __name__ == "__main__":
    main(sys.argv)
